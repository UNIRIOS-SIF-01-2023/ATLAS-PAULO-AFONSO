-- Tabelas do Atlas Urbano (MariaDB). O scripts/db.sh aplica este arquivo em
-- ATLAS (produção, lido pela API) e em ATLAS_STAGE (rascunho da importação).
-- Geometrias em SIRGAS 2000 (4674), guardadas como chegam: x = lon, y = lat.

CREATE TABLE IF NOT EXISTS USUARIOS (
    ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(100) NOT NULL UNIQUE,
    SENHA VARCHAR(255) NOT NULL,
    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
    CRIADO_EM DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP()
) ENGINE=INNODB;

CREATE TABLE IF NOT EXISTS CARGAS (
    ID SMALLINT UNSIGNED NOT NULL AUTO_INCREMENT,
    INICIADA_EM DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONCLUIDA_EM DATETIME NULL,
    PARAMETROS JSON NOT NULL,
    ARQUIVOS JSON NOT NULL,
    CONTAGENS JSON NULL,
    PRIMARY KEY (ID)
) ENGINE=INNODB;

CREATE TABLE IF NOT EXISTS FONTES (
    ID TINYINT UNSIGNED NOT NULL AUTO_INCREMENT,
    NOME VARCHAR(48) NOT NULL,
    LICENCA VARCHAR(24) NOT NULL,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FONTE_NOME (NOME)
) ENGINE=INNODB;

CREATE TABLE IF NOT EXISTS BAIRROS (
    ID SMALLINT UNSIGNED NOT NULL AUTO_INCREMENT,
    NOME VARCHAR(40) NOT NULL,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_BAIRRO_NOME (NOME)
) ENGINE=INNODB;

CREATE TABLE IF NOT EXISTS LOCALIDADES (
    ID SMALLINT UNSIGNED NOT NULL AUTO_INCREMENT,
    NOME VARCHAR(40) NOT NULL,
    BAIRRO_ID SMALLINT UNSIGNED NOT NULL,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_LOCALIDADE_NOME (NOME),
    FOREIGN KEY (BAIRRO_ID) REFERENCES BAIRROS (ID)
) ENGINE=INNODB;

CREATE TABLE IF NOT EXISTS EDIFICACOES (
    ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
    FONTE_ID TINYINT UNSIGNED NOT NULL,
    BAIRRO_ID SMALLINT UNSIGNED NULL,
    TIPO_USO ENUM('residencial','comercial','servico','religioso','institucional','hospedagem','agropecuario','desconhecido') NOT NULL DEFAULT 'desconhecido',
    ORIGEM_TIPO ENUM('cnefe','overture_subtype','overture_class','sem_dado') NOT NULL DEFAULT 'sem_dado',
    USO_MISTO BOOLEAN NOT NULL DEFAULT FALSE,
    N_ENDERECOS SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    NUM_PAVIMENTOS TINYINT UNSIGNED NULL,
    CONFIANCA_FONTE DECIMAL(4,3) NULL,
    CONCORDANCIA_FONTES ENUM('concordam','divergem','so_uma_fonte') NULL,
    NIVEL_VERIFICACAO ENUM('automatico','conferido_tela','conferido_campo') NOT NULL DEFAULT 'automatico',
    PRIORIDADE_CAMPO TINYINT UNSIGNED NULL,
    GEOM GEOMETRY REF_SYSTEM_ID=4674 NOT NULL,
    PONTO_ROTULO POINT REF_SYSTEM_ID=4674 NOT NULL,
    -- O MariaDB calcula ST_AREA no plano (graus²). shortcut: escala por
    -- 111.320 m/grau corrigida pela latitude do centroide (erro < 1% no
    -- município); troque por área geodésica se AREA_M2 virar critério fino.
    AREA_M2 DECIMAL(9,2) AS (ROUND(ST_AREA(GEOM) * POW(111320, 2)
        * COS(RADIANS(ST_Y(ST_CENTROID(GEOM)))), 2)) STORED,
    PRIMARY KEY (ID),
    SPATIAL INDEX SX_EDIFICACAO_GEOM (GEOM),
    SPATIAL INDEX SX_EDIFICACAO_PONTO (PONTO_ROTULO),
    FOREIGN KEY (FONTE_ID)  REFERENCES FONTES (ID),
    FOREIGN KEY (BAIRRO_ID) REFERENCES BAIRROS (ID),
    CHECK (ST_GEOMETRYTYPE(GEOM) IN ('POLYGON','MULTIPOLYGON')),
    CHECK (CONFIANCA_FONTE BETWEEN 0 AND 1)
) ENGINE=INNODB;

CREATE TABLE IF NOT EXISTS EDIFICACAO_ORIGEM (
    EDIFICACAO_ID INT UNSIGNED NOT NULL,
    ID_ORIGEM VARCHAR(64) CHARACTER SET ASCII COLLATE ASCII_BIN NOT NULL,
    FONTES JSON NOT NULL,
    ATRIBUTOS JSON NULL,
    PRIMARY KEY (EDIFICACAO_ID),
    UNIQUE KEY UK_EDIFICACAO_ORIGEM (ID_ORIGEM),
    FOREIGN KEY (EDIFICACAO_ID) REFERENCES EDIFICACOES (ID) ON DELETE CASCADE
) ENGINE=INNODB;

CREATE TABLE IF NOT EXISTS ENDERECOS (
    ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
    COD_UNICO INT UNSIGNED NOT NULL,
    COD_ESPECIE TINYINT UNSIGNED NOT NULL,
    COD_TIPO_ESPECI SMALLINT UNSIGNED NULL,
    TIPO_USO ENUM('residencial','comercial','servico','religioso','institucional','hospedagem','agropecuario','desconhecido')
    AS (ELT(COD_ESPECIE, 'residencial','hospedagem','agropecuario','institucional','servico','comercial','desconhecido','religioso')) VIRTUAL,
    COD_SETOR CHAR(16) CHARACTER SET ASCII NOT NULL,
    NUM_QUADRA SMALLINT UNSIGNED NULL,
    NUM_FACE SMALLINT UNSIGNED NULL,
    CEP CHAR(8) CHARACTER SET ASCII NULL,
    LOCALIDADE_ID SMALLINT UNSIGNED NOT NULL,
    LOGRADOURO_NUM VARCHAR(80) NOT NULL,
    COMPLEMENTO VARCHAR(60) NULL,
    ESTABELECIMENTO VARCHAR(80) NULL,
    NV_GEO_COORD TINYINT UNSIGNED NOT NULL,
    PT POINT REF_SYSTEM_ID=4674 NOT NULL,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_ENDERECO_NATURAL (COD_UNICO, COD_ESPECIE),
    SPATIAL INDEX SX_ENDERECO_PT (PT),
    FULLTEXT INDEX FT_ENDERECO (LOGRADOURO_NUM, ESTABELECIMENTO),
    KEY IX_ENDERECO_SETOR (COD_SETOR),
    FOREIGN KEY (LOCALIDADE_ID) REFERENCES LOCALIDADES (ID),
    CHECK (COD_ESPECIE BETWEEN 1 AND 8)
) ENGINE=INNODB;

CREATE TABLE IF NOT EXISTS ENDERECO_EDIFICACAO (
    ENDERECO_ID INT UNSIGNED NOT NULL,
    EDIFICACAO_ID INT UNSIGNED NOT NULL,
    METODO ENUM('contido','tolerancia') NOT NULL,
    DISTANCIA_M DECIMAL(5,2) NOT NULL DEFAULT 0,
    PRIMARY KEY (ENDERECO_ID),
    KEY IX_EE_EDIFICACAO (EDIFICACAO_ID),
    FOREIGN KEY (ENDERECO_ID) REFERENCES ENDERECOS (ID) ON DELETE CASCADE,
    FOREIGN KEY (EDIFICACAO_ID) REFERENCES EDIFICACOES (ID) ON DELETE CASCADE
) ENGINE=INNODB;

CREATE TABLE IF NOT EXISTS AGG_BAIRRO_TIPO (
    BAIRRO_NOME VARCHAR(40) NOT NULL,
    TIPO_USO ENUM('residencial','comercial','servico','religioso','institucional','hospedagem','agropecuario','desconhecido') NOT NULL,
    N_EDIFICACOES INT UNSIGNED NOT NULL,
    N_ENDERECOS INT UNSIGNED NOT NULL,
    AREA_SOMA_M2 DECIMAL(12,2) NOT NULL,
    PRIMARY KEY (BAIRRO_NOME, TIPO_USO)
) ENGINE=INNODB;
